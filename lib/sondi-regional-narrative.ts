// SONDI_78DW_NATIONAL_REGIONAL_NARRATIVE
// National, evidence-dependent reader. No invented depth intervals.

export function buildSondiReadableRegionalNarrative(
  sourceParagraphs: string[],
  preserveExisting = false
): string[] {
  const original = sourceParagraphs.filter(
    p => typeof p === "string" && p.trim().length > 0
  );

  if (preserveExisting) return original;

  const text = original.join(" ").toLocaleLowerCase("bg-BG");
  const result: string[] = [];

  const has = (pattern: RegExp) => pattern.test(text);

  const young = has(
    /кватернер|алувиал|речни нанос|льос|чакъл|пясъц|пясък|глин/iu
  );
  const sediment = has(
    /мезозой|седимент|пясъчник|алевролит|конгломерат|мергел/iu
  );
  const intrusive = has(
    /гранит|гранодиорит|диорит|сиенит|габро/iu
  );
  const altered = has(
    /филит|шист|кварцит|метабазит|гнайс|метаморф/iu
  );
  const carbonate = has(
    /варовик|варовици|доломит|мрамор|карбонат/iu
  );
  const volcanic = has(
    /вулканит|андезит|базалт|риолит|туф/iu
  );

  const groups: string[] = [];

  if (young) groups.push("по-млади земни наслаги");
  if (sediment) groups.push("седиментни скали");
  if (intrusive) groups.push("магмени скали");
  if (altered) groups.push("преобразувани по-стари скали");
  if (carbonate) groups.push("карбонатни скали");
  if (volcanic) groups.push("вулканични скали");

  if (groups.length === 0) {
    return original.filter(p =>
      !/друг тип геоложка основа/iu.test(p)
    );
  }

  result.push(
    "Наличните геоложки сведения за проучените части " +
    "на района показват разнообразен скален строеж, " +
    "в който са описани " +
    groups.join(", ") + ". " +
    "Това са различни по произход и свойства " +
    "материали, които могат да се срещат " +
    "при различни геоложки условия."
  );

  if (young) {
    const examples: string[] = [];
    if (has(/кватернер/iu)) {
      examples.push(
        "кватернерни отложения — сравнително млади наслаги"
      );
    }
    if (has(/пяс|чакъл/iu)) {
      examples.push("пясъчни и чакълести материали");
    }
    if (has(/глин/iu)) {
      examples.push("глинести материали");
    }
    if (has(/льос/iu)) {
      examples.push("льос — фин праховиден материал");
    }

    result.push(
      "По-младите земни наслаги в регионалните " +
      "проучвания са представени от " +
      (examples.length
        ? examples.join(", ")
        : "различни повърхностни отложения") +
      ". Те могат да се различават по плътност, " +
      "устойчивост и способност да пропускат вода. " +
      "Съставът им не е непременно еднакъв " +
      "във всички части на района."
    );
  }

  if (sediment) {
    const examples: string[] = [];

    if (has(/мезозой/iu)) {
      examples.push(
        "мезозойски седименти — скали, образувани " +
        "през по-стар геоложки период"
      );
    }
    if (has(/пясъчник/iu)) {
      examples.push("пясъчници — споени пясъчни зърна");
    }
    if (has(/алевролит/iu)) {
      examples.push(
        "алевролити — скали от уплътнени фини частици"
      );
    }
    if (has(/конгломерат/iu)) {
      examples.push(
        "конгломерати — споени по-едри скални късове"
      );
    }

    result.push(
      "В проучените части на района са описани " +
      (examples.length
        ? examples.join("; ")
        : "седиментни скални комплекси") +
      ". Тези скали са се образували чрез " +
      "натрупване и последващо уплътняване " +
      "или спояване на материали. " +
      "При сондиране е възможно да имат " +
      "различна здравина."
    );
  }

  if (intrusive) {
    const names: string[] = [];
    if (has(/гранодиорит/iu)) names.push("гранодиорити");
    if (has(/гранит/iu) && !has(/гранодиорит/iu))
      names.push("гранити");
    if (has(/габро/iu)) names.push("габра");
    if (has(/сиенит/iu)) names.push("сиенити");
    if (has(/диорит/iu) && !has(/гранодиорит/iu))
      names.push("диорити");

    result.push(
      "Сред документираните магмени скали са " +
      (names.length ? names.join(", ") : "твърди магмени скали") +
      ". Те са се образували при охлаждане " +
      "и втвърдяване на магмен материал. " +
      "Обикновено са по-здрави от рохкавите наслаги, " +
      "но на места могат да бъдат изветрели, " +
      "напукани или раздробени."
    );
  }

  if (altered) {
    const names: string[] = [];

    if (has(/филит/iu)) {
      names.push("филити — финослоести преобразувани скали");
    }
    if (has(/кварцит/iu)) {
      names.push("кварцити — много твърди скали, богати на кварц");
    }
    if (has(/метабазит/iu)) {
      names.push("метабазити — преобразувани магмени скали");
    }
    if (has(/гнайс/iu)) {
      names.push("гнайси — преобразувани скали с ивичест строеж");
    }

    result.push(
      "В регионалните сведения се срещат и " +
      (names.length
        ? names.join("; ")
        : "преобразувани скални комплекси") +
      ". Те са претърпели промени под влияние " +
      "на висока температура, налягане или " +
      "геоложки движения. При сондиране " +
      "значение имат здравината, напукаността " +
      "и посоката на скалните плоскости."
    );
  }

  if (carbonate) {
    result.push(
      "Карбонатните скали в регионалните сведения " +
      "могат да включват варовици, доломити " +
      "или мрамори според описаното проучване. " +
      "При някои от тези скали пукнатините " +
      "и разтворените участъци могат да имат " +
      "значение за движението на водата. " +
      "Това не доказва наличие на вода " +
      "под конкретния имот."
    );
  }

  if (volcanic) {
    result.push(
      "Описаните вулканични материали са " +
      "свързани с древна вулканична дейност. " +
      "Тяхната устойчивост и напуканост " +
      "могат да се различават между отделните " +
      "участъци на района."
    );
  }

  const practical: string[] = [];

  if (young) {
    practical.push(
      "По-рохкавите наслаги могат да изискват " +
      "внимание към устойчивостта на стените."
    );
  }
  if (intrusive || altered || volcanic) {
    practical.push(
      "По-твърдите скали могат да изискват " +
      "различен начин на пробиване."
    );
  }
  if (sediment || carbonate) {
    practical.push(
      "При споените и напуканите скали значение " +
      "имат плътността и състоянието на " +
      "отделните участъци."
    );
  }

  result.push(
    "За практическото планиране на сондаж " +
    practical.join(" ") + " " +
    "Регионалните сведения описват проучени " +
    "части от района. Те не означават, че " +
    "всички изброени материали се намират " +
    "един под друг на избраните координати."
  );

  return result;
}
