// The zones and source references are read from the existing verified runtime model.
// These cards are presentation-only; no stratigraphic contacts are calculated here.
export function getVratsaRegionReport(zoneId: string | null | undefined, municipality: string | null | undefined): VratsaRegionReportCard[] {
  if (!zoneId || !municipality || !summaries[municipality]) return [];
  const zones = model.zones as Record<string, any>;
  const zone = zones[zoneId];
  if (!zone || !Array.isArray(zone.municipalities) || !zone.municipalities.includes(municipality)) return [];
  const sourceIds = new Set<string>();
  const addSources = (list: unknown) => {
    if (Array.isArray(list)) for (const s of list) if (typeof s === "string") sourceIds.add(s);
  };
  addSources(zone.source_ids);
  for (const item of zone.evidence ?? []) addSources(item.source_ids);
  for (const item of zone.regional_structural_controls ?? []) addSources(item.source_ids);
  addSources(zone.regional_formation_thickness?.source_ids);
  addSources(zone.paleovalley_guard?.source_ids);
  const local = zone.municipality_models?.[municipality];
  addSources(local?.source_ids);
  const primary = summaries[municipality];
  const result: VratsaRegionReportCard[] = [{
    id: `${zoneId}-${municipality}-context`,
    title: primary.title,
    informationType: "Документиран регионален литоложки и структурен контекст",
    paragraphs: primary.descriptions,
    sources: [...sourceIds]
  }];
  if (municipality === "Козлодуй") {
    result.push({
      id: `${zoneId}-local-model`,
      title: "Козлодуй — локални модели и сравнителни разрези",
      informationType: "Пространствена и сондажна геоложка информация",
      paragraphs: [
        "При плитките проучвания са установени льос (фин прахов материал, натрупан от вятъра), глина, пясък и чакъл. На някои от проучените места под тях е описан преход към Брусарската свита — по-стара група глинести и песъчливи пластове.",
        "В Маричин валог са проучени плитки скални пластове, но точните места на отделните разрези не са потвърдени. Затова те не се приемат за еднакви под всички имоти в общината.",
        "Дълбоките проучвателни сондажи Р-12 и Р-13 носят името „Козлодуй“, но се намират в община Вълчедръм, област Монтана. Те могат да служат само за по-широко сравнение, не като доказателство за скалите точно под Козлодуй."
      ],
      sources: [...sourceIds]
    });
  }
  if (zoneId === "VRA-Z02") {
    const formation = zone.regional_formation_thickness?.formations ?? [];
    if (formation.length) {
      result.push({
        id: `${zoneId}-${municipality}-formation-thickness`,
        title: "Северна равнина — мощности и структурни промени",
        informationType: "Регионални мощности на свити, не дълбочини от повърхността",
        paragraphs: [
          "Проучванията описват Фуренската, Белослатинската и Брусарската свита (отделни групи скални пластове). Тяхната дебелина е различна в отделните части на Северозападна България.",
          "Старият релеф и по-ниските части на земните пластове могат да са запълнени с по-дебели неогенски наслаги. Дебелината на една свита обаче не показва на колко метра започва тя под конкретния имот."
        ],
        sources: [...sourceIds]
      });
    }
  }

  // SONDI_VRATSA_READER_OVERVIEW_63CU
  // Merge presentation cards, not source geology or depth models.
  const paragraphs = Array.from(new Set(
    result.flatMap(card => card.paragraphs)
      .map(paragraph => paragraph.trim())
      .filter(Boolean)
  ));

  const sources = Array.from(new Set(
    result.flatMap(card => card.sources)
      .filter(Boolean)
  ));

  return [{
    id: `${zoneId}-${municipality}-reader-overview`,
    title: `Регионален геоложки анализ — ${municipality}`,
    informationType: "Геоложки строеж и практическо значение",
    paragraphs,
    sources
  }];
}
